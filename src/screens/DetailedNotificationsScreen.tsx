import { ArrowLeft, Bell, Filter, Search, CheckCheck, Trash2 } from "lucide-react";
import { NotificationCard } from "../oikos/NotificationCard";
import { GlassCard } from "../oikos/GlassCard";
import { Tabs, TabsContent, TabsList, TabsTrigger } from "../ui/tabs";
import { useState } from "react";

export function DetailedNotificationsScreen({ onBack }: { onBack: () => void }) {
  const [searchQuery, setSearchQuery] = useState("");
  const [filterType, setFilterType] = useState<"all" | "alert" | "success" | "info">("all");

  const notifications = {
    urgent: [
      {
        id: "1",
        title: "Schedule Conflict Detected",
        message: "Soccer practice overlaps with dentist appointment on Monday at 3pm. AI has suggested 2 resolution options.",
        type: "alert" as const,
        time: "5 min ago",
        urgent: true,
        read: false
      },
      {
        id: "2",
        title: "High Priority Task Overdue",
        message: "Buy birthday gift for Sarah was due yesterday. Would you like to reschedule?",
        type: "alert" as const,
        time: "1 hour ago",
        urgent: true,
        read: false
      }
    ],
    today: [
      {
        id: "3",
        title: "Task Completed",
        message: "John completed 'Grocery shopping'. 12/15 items checked off the list.",
        type: "success" as const,
        time: "2 hours ago",
        read: false
      },
      {
        id: "4",
        title: "Meal Plan Ready",
        message: "Your weekly meal plan has been generated by Grocery Agent. 8 recipes added with shopping list.",
        type: "info" as const,
        time: "4 hours ago",
        read: true
      },
      {
        id: "5",
        title: "Event Starting Soon",
        message: "Team Meeting starts in 30 minutes. Location: Office, Attendees: John, Sarah",
        type: "info" as const,
        time: "6 hours ago",
        read: true
      },
      {
        id: "6",
        title: "AI Optimization Complete",
        message: "Task Agent has redistributed 5 tasks based on family availability. Estimated time savings: 2 hours.",
        type: "success" as const,
        time: "7 hours ago",
        read: false
      }
    ],
    earlier: [
      {
        id: "7",
        title: "Calendar Synced",
        message: "Successfully synced with Google Calendar. 23 events imported.",
        type: "success" as const,
        time: "Yesterday at 4:30 PM",
        read: true
      },
      {
        id: "8",
        title: "New Family Member Added",
        message: "Mike Doe joined your household. They now have access to shared tasks and calendars.",
        type: "info" as const,
        time: "2 days ago",
        read: true
      },
      {
        id: "9",
        title: "Weekly Report Available",
        message: "Your household productivity report for last week is ready. View insights and analytics.",
        type: "info" as const,
        time: "3 days ago",
        read: true
      },
      {
        id: "10",
        title: "Reminder Settings Updated",
        message: "Reminder Agent preferences have been updated. You'll now receive notifications 1 hour before events.",
        type: "success" as const,
        time: "4 days ago",
        read: true
      }
    ]
  };

  const allNotifications = [...notifications.urgent, ...notifications.today, ...notifications.earlier];
  const unreadCount = allNotifications.filter(n => !n.read).length;

  const filterNotifications = (notifList: any[]) => {
    let filtered = notifList;

    if (filterType !== "all") {
      filtered = filtered.filter(n => n.type === filterType);
    }

    if (searchQuery) {
      filtered = filtered.filter(n =>
        n.title.toLowerCase().includes(searchQuery.toLowerCase()) ||
        n.message.toLowerCase().includes(searchQuery.toLowerCase())
      );
    }

    return filtered;
  };

  return (
    <div className="min-h-screen flex flex-col bg-gradient-to-br from-[#FFF5F0] via-[#E8F4F8] to-[#F0F8FF]">
      {/* Header */}
      <div className="glass-card rounded-none p-4 flex items-center gap-3 sticky top-0 z-10">
        <button onClick={onBack}>
          <ArrowLeft className="w-6 h-6" />
        </button>
        <Bell className="w-6 h-6 text-primary" />
        <h2>Notifications</h2>
        <div className="ml-auto flex items-center gap-2">
          {unreadCount > 0 && (
            <span className="px-2 py-1 rounded-full bg-alert text-white text-xs font-medium">
              {unreadCount}
            </span>
          )}
        </div>
      </div>

      <div className="flex-1 overflow-auto p-4 pb-24 space-y-4">
        {/* Quick Actions */}
        <div className="grid grid-cols-2 gap-3">
          <button className="glass-card p-3 flex items-center justify-center gap-2 hover:bg-white/50 transition-colors">
            <CheckCheck className="w-4 h-4 text-success" />
            <span className="text-sm">Mark All Read</span>
          </button>
          <button className="glass-card p-3 flex items-center justify-center gap-2 hover:bg-white/50 transition-colors">
            <Trash2 className="w-4 h-4 text-alert" />
            <span className="text-sm">Clear Read</span>
          </button>
        </div>

        {/* Search & Filter */}
        <div className="space-y-3">
          <div className="glass-card p-3 flex items-center gap-2">
            <Search className="w-5 h-5 text-muted-foreground" />
            <input
              type="text"
              placeholder="Search notifications..."
              value={searchQuery}
              onChange={(e) => setSearchQuery(e.target.value)}
              className="flex-1 bg-transparent outline-none text-sm"
            />
          </div>

          <div className="flex gap-2 overflow-x-auto pb-2">
            <button
              onClick={() => setFilterType("all")}
              className={`px-4 py-2 rounded-xl text-sm whitespace-nowrap transition-all ${
                filterType === "all"
                  ? 'bg-primary text-primary-foreground'
                  : 'glass-card'
              }`}
            >
              All
            </button>
            <button
              onClick={() => setFilterType("alert")}
              className={`px-4 py-2 rounded-xl text-sm whitespace-nowrap transition-all ${
                filterType === "alert"
                  ? 'bg-alert text-white'
                  : 'glass-card'
              }`}
            >
              Alerts
            </button>
            <button
              onClick={() => setFilterType("success")}
              className={`px-4 py-2 rounded-xl text-sm whitespace-nowrap transition-all ${
                filterType === "success"
                  ? 'bg-success text-white'
                  : 'glass-card'
              }`}
            >
              Success
            </button>
            <button
              onClick={() => setFilterType("info")}
              className={`px-4 py-2 rounded-xl text-sm whitespace-nowrap transition-all ${
                filterType === "info"
                  ? 'bg-accent text-white'
                  : 'glass-card'
              }`}
            >
              Info
            </button>
          </div>
        </div>

        {/* Notifications Tabs */}
        <Tabs defaultValue="all" className="w-full">
          <TabsList className="glass-card w-full grid grid-cols-3 mb-4">
            <TabsTrigger value="all">
              All ({filterNotifications(allNotifications).length})
            </TabsTrigger>
            <TabsTrigger value="unread">
              Unread ({unreadCount})
            </TabsTrigger>
            <TabsTrigger value="read">
              Read ({allNotifications.length - unreadCount})
            </TabsTrigger>
          </TabsList>

          <TabsContent value="all" className="space-y-4">
            {filterNotifications(notifications.urgent).length > 0 && (
              <div className="space-y-3">
                <h3 className="text-sm font-medium text-alert px-1">Urgent</h3>
                {filterNotifications(notifications.urgent).map(notif => (
                  <NotificationCard key={notif.id} {...notif} />
                ))}
              </div>
            )}

            {filterNotifications(notifications.today).length > 0 && (
              <div className="space-y-3">
                <h3 className="text-sm font-medium text-muted-foreground px-1">Today</h3>
                {filterNotifications(notifications.today).map(notif => (
                  <NotificationCard key={notif.id} {...notif} />
                ))}
              </div>
            )}

            {filterNotifications(notifications.earlier).length > 0 && (
              <div className="space-y-3">
                <h3 className="text-sm font-medium text-muted-foreground px-1">Earlier</h3>
                {filterNotifications(notifications.earlier).map(notif => (
                  <NotificationCard key={notif.id} {...notif} />
                ))}
              </div>
            )}

            {filterNotifications(allNotifications).length === 0 && (
              <GlassCard className="p-8 text-center">
                <Bell className="w-12 h-12 text-muted-foreground mx-auto mb-3 opacity-50" />
                <p className="text-sm text-muted-foreground">No notifications found</p>
              </GlassCard>
            )}
          </TabsContent>

          <TabsContent value="unread" className="space-y-3">
            {allNotifications.filter(n => !n.read).length === 0 ? (
              <GlassCard className="p-8 text-center">
                <CheckCheck className="w-12 h-12 text-success mx-auto mb-3 opacity-50" />
                <p className="text-sm text-muted-foreground">All caught up!</p>
              </GlassCard>
            ) : (
              allNotifications.filter(n => !n.read).map(notif => (
                <NotificationCard key={notif.id} {...notif} />
              ))
            )}
          </TabsContent>

          <TabsContent value="read" className="space-y-3">
            {allNotifications.filter(n => n.read).length === 0 ? (
              <GlassCard className="p-8 text-center">
                <Bell className="w-12 h-12 text-muted-foreground mx-auto mb-3 opacity-50" />
                <p className="text-sm text-muted-foreground">No read notifications</p>
              </GlassCard>
            ) : (
              allNotifications.filter(n => n.read).map(notif => (
                <NotificationCard key={notif.id} {...notif} />
              ))
            )}
          </TabsContent>
        </Tabs>
      </div>
    </div>
  );
}
